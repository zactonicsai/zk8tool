package main

import (
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const heredocEnd = "KUBEGEN_EOF"

var shellSafeRe = regexp.MustCompile(`^[A-Za-z0-9_./:=@%+,-]+$`)

// q quotes a value for use as a single shell word.
func q(s string) string {
	if shellSafeRe.MatchString(s) {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// qPath quotes a file path, keeping a leading ~/ expandable.
func qPath(p string) string {
	if rest, ok := strings.CutPrefix(p, "~/"); ok {
		return `"$HOME"/` + q(rest)
	}
	return q(p)
}

// y quotes a string for embedding in generated YAML.
func y(s string) string { return strconv.Quote(s) }

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// kvList renders a map as sorted "k=v" words.
func kvList(m map[string]string) []string {
	var out []string
	for _, k := range sortedKeys(m) {
		out = append(out, k+"="+m[k])
	}
	return out
}

// taintStrings renders taints as key=value:Effect.
func taintStrings(ts []Taint) []string {
	var out []string
	for _, t := range ts {
		s := t.Key
		if t.Value != "" {
			s += "=" + t.Value
		}
		out = append(out, s+":"+t.Effect)
	}
	return out
}

type script struct{ b strings.Builder }

func (s *script) line(format string, a ...any) {
	if len(a) == 0 {
		s.b.WriteString(format + "\n")
		return
	}
	fmt.Fprintf(&s.b, format+"\n", a...)
}

func (s *script) step(title string) {
	s.line("")
	s.line("echo %s", q("==> "+title))
}

// cmd writes one command. Each group of words goes on its own line; every
// word is shell-quoted.
func (s *script) cmd(groups ...[]string) {
	var lines []string
	for _, g := range groups {
		if len(g) == 0 {
			continue
		}
		words := make([]string, len(g))
		for i, w := range g {
			words[i] = q(w)
		}
		lines = append(lines, strings.Join(words, " "))
	}
	s.line(strings.Join(lines, " \\\n  "))
}

// raw marks a word that must not be quoted (e.g. "$CONFIG_FILE").
// It is substituted after quoting.
const rawConfigFile = "@@CONFIG_FILE@@"
const rawKubeconfig = "@@KUBECONFIG_OUT@@"

func (s *script) String() string {
	out := s.b.String()
	out = strings.ReplaceAll(out, q(rawConfigFile), `"$CONFIG_FILE"`)
	out = strings.ReplaceAll(out, q(rawKubeconfig), `"$KUBECONFIG_OUT"`)
	return out
}

// configFile writes content to a temp file referenced as $CONFIG_FILE.
func (s *script) configFile(content string) {
	s.line(`CONFIG_FILE="$(mktemp)"`)
	s.line(`trap 'rm -f "$CONFIG_FILE"' EXIT`)
	s.line(`cat > "$CONFIG_FILE" <<'%s'`, heredocEnd)
	s.b.WriteString(strings.TrimRight(content, "\n") + "\n")
	s.line(heredocEnd)
}

// opt returns {flag, value} when value is set.
func opt(flag, value string) []string {
	if value == "" {
		return nil
	}
	return []string{flag, value}
}

// flagIf returns {flag} when on is true.
func flagIf(flag string, on bool) []string {
	if !on {
		return nil
	}
	return []string{flag}
}

// multi returns {flag, values...} when there are values.
func multi(flag string, values []string) []string {
	if len(values) == 0 {
		return nil
	}
	return append([]string{flag}, values...)
}

// generate renders the shell script that creates the cluster.
func generate(c *Config, source string, tools []Tool) string {
	s := &script{}
	s.line("#!/usr/bin/env bash")
	s.line("# Generated by kubegen from %s - re-generate instead of editing.", source)
	s.line("# Creates the %s cluster %q.", c.Provider, c.Name)
	s.line("set -euo pipefail")
	s.line("")
	s.line(`die() { echo "error: $*" >&2; exit 1; }`)
	s.line("")
	s.line("# Required tools")
	s.line("missing=0")
	s.line("need() {")
	s.line(`  command -v "$1" >/dev/null 2>&1 && return`)
	s.line(`  echo "error: required tool '$1' is not installed or not in PATH" >&2`)
	s.line(`  echo "       install it from: $2" >&2`)
	s.line("  missing=1")
	s.line("}")
	for _, t := range tools {
		s.line("need %s %s", q(t.Binary), q(t.URL))
	}
	s.line(`[ "$missing" -eq 0 ] || exit 127`)

	hasKubeconfig := c.Kubeconfig.Path != "" || c.Provider == "vks"
	if hasKubeconfig {
		path := c.Kubeconfig.Path
		if path == "" {
			path = "./" + c.Name + ".kubeconfig"
		}
		s.line("")
		s.line("KUBECONFIG_OUT=%s", qPath(path))
	}

	verify := true
	switch c.Provider {
	case "kind":
		genKind(s, c)
	case "aks":
		genAKS(s, c)
		verify = !c.AKS.PrivateCluster
	case "eks":
		genEKS(s, c)
		verify = c.EKS.EndpointPublicAccess == nil || *c.EKS.EndpointPublicAccess
	case "vks":
		genVKS(s, c)
	case "dks":
		genDKS(s, c)
	case "gks":
		genGKS(s, c)
	}

	if verify {
		s.step("Verifying access to " + c.Name)
		if hasKubeconfig {
			s.cmd([]string{"kubectl", "--kubeconfig", rawKubeconfig, "get", "nodes", "-o", "wide"})
		} else {
			s.cmd([]string{"kubectl", "get", "nodes", "-o", "wide"})
		}
	} else {
		s.line("")
		s.line("# The API server is private; run kubectl from inside the cluster network.")
	}
	s.line("")
	if hasKubeconfig {
		s.line(`echo "Cluster %s is ready. Kubeconfig: $KUBECONFIG_OUT"`, c.Name)
	} else {
		s.line(`echo "Cluster %s is ready."`, c.Name)
	}
	return s.String()
}

func genKind(s *script, c *Config) {
	k := c.Kind
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	w("kind: Cluster")
	w("apiVersion: kind.x-k8s.io/v1alpha4")
	if k.APIServerAddress != "" || k.APIServerPort != 0 || k.PodSubnet != "" || k.ServiceSubnet != "" || k.DisableDefaultCNI {
		w("networking:")
		if k.APIServerAddress != "" {
			w("  apiServerAddress: %s", y(k.APIServerAddress))
		}
		if k.APIServerPort != 0 {
			w("  apiServerPort: %d", k.APIServerPort)
		}
		if k.PodSubnet != "" {
			w("  podSubnet: %s", y(k.PodSubnet))
		}
		if k.ServiceSubnet != "" {
			w("  serviceSubnet: %s", y(k.ServiceSubnet))
		}
		if k.DisableDefaultCNI {
			w("  disableDefaultCNI: true")
		}
	}

	ports := k.ExtraPortMappings
	if k.IngressReady {
		ports = append([]PortMapping{{80, 80, "TCP"}, {443, 443, "TCP"}}, ports...)
	}
	controlPlanes := max(k.ControlPlaneNodes, 1)
	w("nodes:")
	for i := 0; i < controlPlanes; i++ {
		w("  - role: control-plane")
		if i > 0 {
			continue
		}
		if k.IngressReady {
			w("    labels:")
			w("      ingress-ready: \"true\"")
		}
		if len(ports) > 0 {
			w("    extraPortMappings:")
			for _, p := range ports {
				w("      - containerPort: %d", p.ContainerPort)
				w("        hostPort: %d", p.HostPort)
				if p.Protocol != "" {
					w("        protocol: %s", p.Protocol)
				}
			}
		}
	}
	for i := 0; i < k.WorkerNodes; i++ {
		w("  - role: worker")
	}

	image := k.NodeImage
	if image == "" && c.KubernetesVersion != "" {
		image = "kindest/node:v" + strings.TrimPrefix(c.KubernetesVersion, "v")
	}
	wait := k.WaitTimeout
	if wait == "" {
		wait = "120s"
	}

	if k.Runtime == "podman" {
		s.step("Checking Podman")
		s.line("# kind uses Docker unless told otherwise.")
		s.line("export KIND_EXPERIMENTAL_PROVIDER=podman")
		s.line(`podman info >/dev/null 2>&1 || die "Podman is installed but not usable; on macOS/Windows run: podman machine start"`)
	} else {
		s.step("Checking Docker")
		s.line(`docker info >/dev/null 2>&1 || die "Docker is installed but the daemon is not running"`)
	}
	s.step("Creating kind cluster " + c.Name)
	s.configFile(b.String())
	var kubeconfig []string
	if c.Kubeconfig.Path != "" {
		kubeconfig = []string{"--kubeconfig", rawKubeconfig}
	}
	s.cmd(
		[]string{"kind", "create", "cluster", "--name", c.Name},
		[]string{"--config", rawConfigFile},
		opt("--image", image),
		[]string{"--wait", wait},
		kubeconfig,
	)
}

func genAKS(s *script, c *Config) {
	a := c.AKS
	s.step("Checking Azure login")
	s.line(`az account show >/dev/null 2>&1 || die "not logged in to Azure; run: az login"`)
	if a.Subscription != "" {
		s.cmd([]string{"az", "account", "set", "--subscription", a.Subscription})
	}
	if a.CreateResourceGroup {
		s.step("Creating resource group " + a.ResourceGroup)
		s.cmd([]string{"az", "group", "create", "--name", a.ResourceGroup, "--location", c.Region, "--output", "none"})
	}

	autoscale := func(p NodePool) []string {
		if !p.autoscaled() {
			return nil
		}
		return []string{"--enable-cluster-autoscaler",
			"--min-count", strconv.Itoa(p.Autoscaling.Min), "--max-count", strconv.Itoa(p.Autoscaling.Max)}
	}
	disk := func(p NodePool) []string {
		if p.DiskSizeGB == 0 {
			return nil
		}
		return []string{"--node-osdisk-size", strconv.Itoa(p.DiskSizeGB)}
	}

	sys := c.NodePools[0]
	ssh := []string{"--generate-ssh-keys"}
	if a.SSHPublicKeyPath != "" {
		ssh = []string{"--ssh-key-value", a.SSHPublicKeyPath}
	}
	s.step("Creating AKS cluster " + c.Name + " (this takes several minutes)")
	s.cmd(
		[]string{"az", "aks", "create"},
		[]string{"--resource-group", a.ResourceGroup, "--name", c.Name, "--location", c.Region},
		opt("--kubernetes-version", c.KubernetesVersion),
		opt("--tier", a.Tier),
		[]string{"--nodepool-name", sys.Name, "--node-count", strconv.Itoa(sys.initialCount()), "--node-vm-size", sys.Size},
		disk(sys),
		autoscale(sys),
		multi("--zones", sys.Zones),
		multi("--nodepool-labels", kvList(sys.Labels)),
		opt("--nodepool-taints", strings.Join(taintStrings(sys.Taints), ",")),
		opt("--network-plugin", a.NetworkPlugin),
		opt("--network-plugin-mode", a.NetworkPluginMode),
		opt("--network-policy", a.NetworkPolicy),
		flagIf("--network-dataplane=cilium", a.NetworkPolicy == "cilium"),
		opt("--pod-cidr", a.PodCIDR),
		opt("--service-cidr", a.ServiceCIDR),
		opt("--dns-service-ip", a.DNSServiceIP),
		opt("--vnet-subnet-id", a.VnetSubnetID),
		flagIf("--enable-private-cluster", a.PrivateCluster),
		[]string{"--enable-managed-identity"},
		flagIf("--enable-oidc-issuer", a.EnableOIDCIssuer || a.EnableWorkloadIdentity),
		flagIf("--enable-workload-identity", a.EnableWorkloadIdentity),
		opt("--attach-acr", a.AttachACR),
		opt("--admin-username", a.AdminUsername),
		ssh,
		multi("--tags", kvList(c.Tags)),
		[]string{"--output", "none"},
	)

	for _, p := range c.NodePools[1:] {
		var spot []string
		if p.Spot {
			spot = []string{"--priority", "Spot", "--eviction-policy", "Delete", "--spot-max-price", "-1"}
		}
		s.step("Adding node pool " + p.Name)
		s.cmd(
			[]string{"az", "aks", "nodepool", "add"},
			[]string{"--resource-group", a.ResourceGroup, "--cluster-name", c.Name, "--name", p.Name, "--mode", "User"},
			[]string{"--node-count", strconv.Itoa(p.initialCount()), "--node-vm-size", p.Size},
			disk(p),
			autoscale(p),
			multi("--zones", p.Zones),
			multi("--labels", kvList(p.Labels)),
			opt("--node-taints", strings.Join(taintStrings(p.Taints), ",")),
			spot,
			[]string{"--output", "none"},
		)
	}

	s.step("Fetching credentials")
	var file []string
	if c.Kubeconfig.Path != "" {
		file = []string{"--file", rawKubeconfig}
	}
	s.cmd(
		[]string{"az", "aks", "get-credentials", "--resource-group", a.ResourceGroup, "--name", c.Name, "--overwrite-existing"},
		file,
	)
}

func genEKS(s *script, c *Config) {
	e := c.EKS
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	strList := func(items []string) string {
		quoted := make([]string, len(items))
		for i, it := range items {
			quoted[i] = y(it)
		}
		return "[" + strings.Join(quoted, ", ") + "]"
	}
	writeMap := func(indent, key string, m map[string]string) {
		if len(m) == 0 {
			return
		}
		w("%s%s:", indent, key)
		for _, k := range sortedKeys(m) {
			w("%s  %s: %s", indent, y(k), y(m[k]))
		}
	}

	w("apiVersion: eksctl.io/v1alpha5")
	w("kind: ClusterConfig")
	w("metadata:")
	w("  name: %s", y(c.Name))
	w("  region: %s", y(c.Region))
	if c.KubernetesVersion != "" {
		w("  version: %s", y(c.KubernetesVersion))
	}
	writeMap("  ", "tags", c.Tags)
	if len(e.AvailabilityZones) > 0 {
		w("availabilityZones: %s", strList(e.AvailabilityZones))
	}
	if e.WithOIDC {
		w("iam:")
		w("  withOIDC: true")
	}
	if e.VPCCIDR != "" || e.NATGateway != "" || e.EndpointPublicAccess != nil || e.EndpointPrivateAccess != nil {
		w("vpc:")
		if e.VPCCIDR != "" {
			w("  cidr: %s", y(e.VPCCIDR))
		}
		if e.NATGateway != "" {
			w("  nat:")
			w("    gateway: %s", e.NATGateway)
		}
		if e.EndpointPublicAccess != nil || e.EndpointPrivateAccess != nil {
			w("  clusterEndpoints:")
			if e.EndpointPublicAccess != nil {
				w("    publicAccess: %t", *e.EndpointPublicAccess)
			}
			if e.EndpointPrivateAccess != nil {
				w("    privateAccess: %t", *e.EndpointPrivateAccess)
			}
		}
	}
	if len(e.Addons) > 0 {
		w("addons:")
		for _, a := range e.Addons {
			w("  - name: %s", y(a))
		}
	}
	w("managedNodeGroups:")
	for _, p := range c.NodePools {
		minSize, maxSize := p.initialCount(), p.initialCount()
		if p.autoscaled() {
			minSize, maxSize = p.Autoscaling.Min, p.Autoscaling.Max
		}
		w("  - name: %s", y(p.Name))
		w("    instanceType: %s", y(p.Size))
		w("    desiredCapacity: %d", p.initialCount())
		w("    minSize: %d", minSize)
		w("    maxSize: %d", maxSize)
		if p.DiskSizeGB != 0 {
			w("    volumeSize: %d", p.DiskSizeGB)
		}
		if e.AMIFamily != "" {
			w("    amiFamily: %s", y(e.AMIFamily))
		}
		if len(p.Zones) > 0 {
			w("    availabilityZones: %s", strList(p.Zones))
		}
		if e.PrivateNetworking {
			w("    privateNetworking: true")
		}
		if p.Spot {
			w("    spot: true")
		}
		writeMap("    ", "labels", p.Labels)
		if len(p.Taints) > 0 {
			w("    taints:")
			for _, t := range p.Taints {
				w("      - key: %s", y(t.Key))
				if t.Value != "" {
					w("        value: %s", y(t.Value))
				}
				w("        effect: %s", t.Effect)
			}
		}
	}

	profile := opt("--profile", e.Profile)
	s.step("Checking AWS credentials")
	s.line(`%s >/dev/null 2>&1 || die "no valid AWS credentials; run: aws configure (or aws sso login)"`,
		strings.Join(mapQ(append([]string{"aws", "sts", "get-caller-identity"}, profile...)), " "))
	s.step("Creating EKS cluster " + c.Name + " (this takes 15-20 minutes)")
	s.configFile(b.String())
	var kubeconfig []string
	if c.Kubeconfig.Path != "" {
		kubeconfig = []string{"--kubeconfig", rawKubeconfig}
	}
	s.cmd([]string{"eksctl", "create", "cluster", "-f", rawConfigFile}, profile, kubeconfig)
}

func mapQ(words []string) []string {
	out := make([]string, len(words))
	for i, w := range words {
		out[i] = q(w)
	}
	return out
}

func genVKS(s *script, c *Config) {
	v := c.VKS
	apiVersion := v.APIVersion
	if apiVersion == "" {
		apiVersion = "cluster.x-k8s.io/v1beta1"
	}
	replicas := v.ControlPlaneReplicas
	if replicas == 0 {
		replicas = 1
	}

	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("apiVersion: %s", apiVersion)
	w("kind: Cluster")
	w("metadata:")
	w("  name: %s", y(c.Name))
	w("  namespace: %s", y(v.Namespace))
	if len(c.Tags) > 0 {
		w("  labels:")
		for _, k := range sortedKeys(c.Tags) {
			w("    %s: %s", y(k), y(c.Tags[k]))
		}
	}
	w("spec:")
	if v.PodCIDR != "" || v.ServiceCIDR != "" || v.ServiceDomain != "" {
		w("  clusterNetwork:")
		if v.PodCIDR != "" {
			w("    pods:")
			w("      cidrBlocks: [%s]", y(v.PodCIDR))
		}
		if v.ServiceCIDR != "" {
			w("    services:")
			w("      cidrBlocks: [%s]", y(v.ServiceCIDR))
		}
		if v.ServiceDomain != "" {
			w("    serviceDomain: %s", y(v.ServiceDomain))
		}
	}
	w("  topology:")
	w("    class: %s", y(v.ClusterClass))
	if v.ClusterClassNamespace != "" {
		w("    classNamespace: %s", y(v.ClusterClassNamespace))
	}
	w("    version: %s", y(c.KubernetesVersion))
	w("    controlPlane:")
	w("      replicas: %d", replicas)
	w("    variables:")
	w("      - name: vmClass")
	w("        value: %s", y(v.VMClass))
	w("      - name: storageClass")
	w("        value: %s", y(v.StorageClass))
	w("    workers:")
	w("      machineDeployments:")
	for _, p := range c.NodePools {
		w("        - class: node-pool")
		w("          name: %s", y(p.Name))
		if p.autoscaled() {
			// replicas must be left unset when the autoscaler owns the pool
			w("          metadata:")
			w("            annotations:")
			w("              cluster.x-k8s.io/cluster-api-autoscaler-node-group-min-size: %s", y(strconv.Itoa(p.Autoscaling.Min)))
			w("              cluster.x-k8s.io/cluster-api-autoscaler-node-group-max-size: %s", y(strconv.Itoa(p.Autoscaling.Max)))
		} else {
			w("          replicas: %d", p.initialCount())
		}
		if p.Size != "" && p.Size != v.VMClass {
			w("          variables:")
			w("            overrides:")
			w("              - name: vmClass")
			w("                value: %s", y(p.Size))
		}
	}

	if l := v.Login; l != nil {
		switch {
		case l.Method == "kubectl-vsphere":
			s.step("Logging in to Supervisor " + l.Server)
			s.line("# Set KUBECTL_VSPHERE_PASSWORD to avoid the password prompt.")
			s.cmd(
				[]string{"kubectl", "vsphere", "login", "--server", l.Server, "--vsphere-username", l.Username},
				flagIf("--insecure-skip-tls-verify", l.InsecureSkipTLSVerify),
			)
			s.cmd([]string{"kubectl", "config", "use-context", v.Namespace})
		case l.Context != "":
			s.step("Switching to context " + l.Context)
			s.cmd([]string{"kubectl", "config", "use-context", l.Context})
		}
	}
	s.step("Checking access to vSphere Namespace " + v.Namespace)
	s.line(`%s >/dev/null 2>&1 || die %s`,
		strings.Join(mapQ([]string{"kubectl", "get", "clusters", "-n", v.Namespace}), " "),
		q("cannot list clusters in vSphere Namespace "+v.Namespace+"; log in to the Supervisor first"))

	wait := v.WaitTimeout
	if wait == "" {
		wait = "30m"
	}
	condition := "Available"
	if strings.HasSuffix(apiVersion, "/v1beta1") {
		condition = "Ready"
	}
	s.step("Creating VKS cluster " + c.Name)
	s.configFile(b.String())
	s.cmd([]string{"kubectl", "apply", "-f", rawConfigFile})
	s.step("Waiting for the cluster to become ready (up to " + wait + ")")
	s.cmd([]string{"kubectl", "wait", "--for=condition=" + condition, "cluster/" + c.Name, "-n", v.Namespace, "--timeout=" + wait})
	s.step("Fetching credentials")
	s.line(`(umask 077; %s | base64 -d > "$KUBECONFIG_OUT")`,
		strings.Join(mapQ([]string{"kubectl", "get", "secret", c.Name + "-kubeconfig", "-n", v.Namespace, "-o", "jsonpath={.data.value}"}), " "))
}

func genDKS(s *script, c *Config) {
	d := c.DKS
	ctx := opt("--context", d.Context)
	version := c.KubernetesVersion
	if version == "" {
		version = "latest"
	}

	var pools []string
	for _, p := range c.NodePools {
		parts := []string{"name=" + p.Name, "size=" + p.Size, "count=" + strconv.Itoa(p.initialCount())}
		if p.autoscaled() {
			parts = append(parts, "auto-scale=true",
				"min-nodes="+strconv.Itoa(p.Autoscaling.Min), "max-nodes="+strconv.Itoa(p.Autoscaling.Max))
		}
		for _, kv := range kvList(p.Labels) {
			parts = append(parts, "label="+kv)
		}
		for _, t := range taintStrings(p.Taints) {
			parts = append(parts, "taint="+t)
		}
		pools = append(pools, "--node-pool", strings.Join(parts, ";"))
	}
	var tags []string
	for _, k := range sortedKeys(c.Tags) {
		tags = append(tags, "--tag", k+":"+c.Tags[k])
	}

	s.step("Checking DigitalOcean credentials")
	s.line(`%s >/dev/null 2>&1 || die "doctl is not authenticated; run: doctl auth init"`,
		strings.Join(mapQ(append([]string{"doctl", "account", "get"}, ctx...)), " "))
	s.step("Creating DigitalOcean Kubernetes cluster " + c.Name + " (this takes several minutes)")
	groups := [][]string{
		{"doctl", "kubernetes", "cluster", "create", c.Name},
		{"--region", c.Region, "--version", version},
	}
	for i := 0; i < len(pools); i += 2 {
		groups = append(groups, pools[i:i+2])
	}
	groups = append(groups,
		flagIf("--ha", d.HA),
		flagIf("--auto-upgrade", d.AutoUpgrade),
		flagIf("--surge-upgrade", d.SurgeUpgrade),
		opt("--vpc-uuid", d.VPCUUID),
		opt("--maintenance-window", d.MaintenanceWindow),
		tags,
		flagIf("--update-kubeconfig=false", c.Kubeconfig.Path != ""),
		[]string{"--wait"},
		ctx,
	)
	s.cmd(groups...)
	if c.Kubeconfig.Path != "" {
		s.step("Fetching credentials")
		s.line(`(umask 077; %s > "$KUBECONFIG_OUT")`,
			strings.Join(mapQ(append([]string{"doctl", "kubernetes", "cluster", "kubeconfig", "show", c.Name}, ctx...)), " "))
	}
}

func genGKS(s *script, c *Config) {
	g := c.GKS
	// --location takes a region (regional cluster) or a zone (zonal cluster).
	where := []string{"--project", g.Project, "--location", c.Region}

	var channel []string
	if g.ReleaseChannel != "" {
		channel = []string{"--release-channel", g.ReleaseChannel}
	}
	var workloadPool []string
	if g.WorkloadIdentity {
		workloadPool = []string{"--workload-pool", g.Project + ".svc.id.goog"}
	}

	s.step("Checking Google Cloud login")
	s.line(`gcloud auth print-access-token >/dev/null 2>&1 || die "not logged in to Google Cloud; run: gcloud auth login"`)

	// GKE always creates a pool called default-pool with the cluster. It is
	// created small here and removed once the pools from the definition exist,
	// so every pool has the name and settings you asked for.
	s.step("Creating GKE cluster " + c.Name + " (this takes several minutes)")
	s.cmd(
		[]string{"gcloud", "container", "clusters", "create", c.Name},
		where,
		opt("--cluster-version", c.KubernetesVersion),
		channel,
		[]string{"--num-nodes", "1"},
		opt("--network", g.Network),
		opt("--subnetwork", g.Subnetwork),
		[]string{"--enable-ip-alias"},
		opt("--cluster-ipv4-cidr", g.PodCIDR),
		opt("--services-ipv4-cidr", g.ServiceCIDR),
		flagIf("--enable-private-nodes", g.PrivateNodes),
		opt("--master-ipv4-cidr", g.MasterCIDR),
		workloadPool,
		flagIf("--enable-dataplane-v2", g.DataplaneV2),
		opt("--labels", strings.Join(kvList(c.Tags), ",")),
		[]string{"--quiet"},
	)

	for _, p := range c.NodePools {
		var autoscale []string
		if p.autoscaled() {
			autoscale = []string{"--enable-autoscaling",
				"--min-nodes", strconv.Itoa(p.Autoscaling.Min), "--max-nodes", strconv.Itoa(p.Autoscaling.Max)}
		}
		var disk []string
		if p.DiskSizeGB != 0 {
			disk = []string{"--disk-size", strconv.Itoa(p.DiskSizeGB)}
		}
		s.step("Adding node pool " + p.Name)
		s.cmd(
			[]string{"gcloud", "container", "node-pools", "create", p.Name, "--cluster", c.Name},
			where,
			// In a regional cluster this is the number of nodes in EACH zone.
			[]string{"--machine-type", p.Size, "--num-nodes", strconv.Itoa(p.initialCount())},
			disk,
			autoscale,
			opt("--node-locations", strings.Join(p.Zones, ",")),
			opt("--node-labels", strings.Join(kvList(p.Labels), ",")),
			opt("--node-taints", strings.Join(taintStrings(p.Taints), ",")),
			flagIf("--spot", p.Spot),
			[]string{"--quiet"},
		)
	}

	s.step("Removing the temporary default-pool")
	s.cmd([]string{"gcloud", "container", "node-pools", "delete", "default-pool", "--cluster", c.Name}, where, []string{"--quiet"})

	s.step("Fetching credentials")
	get := strings.Join(mapQ(append([]string{"gcloud", "container", "clusters", "get-credentials", c.Name}, where...)), " ")
	if c.Kubeconfig.Path != "" {
		// gcloud writes to the file named by KUBECONFIG.
		s.line(`KUBECONFIG="$KUBECONFIG_OUT" %s`, get)
	} else {
		s.line("%s", get)
	}
}
